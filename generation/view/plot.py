import matplotlib.pyplot as plt
import numpy as np
from matplotlib.colors import ListedColormap


def plot(mat):
    array = np.array(mat)

    cmap = ListedColormap(["#00CC66", "#222222"])  # 0 -> tunnel vert, 1 -> mur noir

    plt.imshow(array, cmap=cmap)
    plt.title("Tunnel")
    plt.axis("off")
    plt.show()


